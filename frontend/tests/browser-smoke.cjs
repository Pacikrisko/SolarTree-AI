const assert = require('node:assert/strict')
const {chromium} = require(process.env.BROWSER_MODULE)
const origin = 'http://127.0.0.1:10000'

async function main() {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH})
  try {
    const page = await browser.newPage({viewport:{width:1440,height:900}})
    const outdated = await browser.newPage()
    await outdated.goto(origin+'/?solixClient=android&build=1')
    const update = outdated.getByRole('link',{name:/Актуализирай|Update/})
    await update.waitFor()
    assert.match(await update.getAttribute('href'), /Solix\.apk$/)
    await outdated.close()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', msg => { if(msg.type()==='error') errors.push(msg.text()) })
    await page.goto(origin)
    await page.locator('#signin-email').waitFor()
    assert.equal(await page.locator('.signin-form').evaluate(form => form.checkValidity()), false)
    assert.equal(await page.evaluate(()=>performance.getEntriesByType('resource').some(r=>/Charts-/.test(new URL(r.name).pathname))),false)
    await page.locator('.signin-reveal').click()
    assert.equal(await page.locator('#signin-password').getAttribute('type'),'text')
    await page.locator('a[href="#/forgot-password"]').click()
    await page.locator('input[autocomplete=email]').waitFor()
    await page.locator('a[href="#/overview"]').click()
    await page.locator('.signin-switch button').click()
    await page.locator('#signin-name').fill('Browser test')
    await page.locator('#signin-email').fill('browser@example.com')
    await page.locator('#signin-password').fill('Test-password-7249')
    await page.locator('.signin-submit').click()
    await page.locator('.dashboard').waitFor()
    assert.equal(await page.title(),'Solix')
    await page.goto(origin+'/#/trees')
    await page.locator('.side-brand a.solix-brand').click()
    await page.waitForURL(/#\/overview$/)
    await page.locator('.dashboard').waitFor()
    await page.locator('.dashboard button').filter({hasText:/Добави дърво|Add tree/i}).first().click()
    const form = page.locator('.pairing-modal form.modal-form')
    await form.locator('input').nth(0).fill('CI-TREE')
    await form.locator('input').nth(1).fill(process.env.TEST_CLAIM)
    await form.locator('button.full').click()
    await form.locator('.paired-model').waitFor()
    await form.locator('input').nth(2).fill('Browser tree')
    await form.locator('input').nth(3).fill('Sofia')
    await form.locator('button[type=submit]').click()
    await form.waitFor({state:'hidden'})
    const token = await page.evaluate(()=>localStorage.getItem('solartree_token'))
    const response = await page.request.get(origin+'/api/trees',{headers:{Authorization:'Bearer '+token}})
    const [tree] = await response.json()
    assert.equal(tree.name,'Browser tree')
    assert.ok(Math.abs(tree.lat-42.70)<0.1 && Math.abs(tree.lng-23.32)<0.1,'Sofia pin')
    const agentPage = await browser.newPage()
    const account = await agentPage.request.post(origin+'/api/auth/register',{data:{
      name:'Test agent',email:'agent-ui@example.com',password:'Test-agent-73591'
    }})
    const agent = await account.json()
    assert.ok(agent.access_token)
    require('node:child_process').execFileSync('psql',[
      'postgresql://postgres:ci_only@127.0.0.1:5432/postgres','-v','ON_ERROR_STOP=1','-c',
      "INSERT INTO support_agents(user_id) SELECT id FROM users WHERE email='agent-ui@example.com'"
    ])
    await agentPage.addInitScript(token=>localStorage.setItem('solartree_token',token),agent.access_token)
    await agentPage.goto(origin+'/#/support')
    await agentPage.locator('.support-desk aside').waitFor()
    await page.goto(origin+'/#/support')
    await page.locator('.desk-channels button').nth(1).click()
    await page.locator('.support-desk select').first().selectOption(String(tree.id))
    await page.locator('.support-desk input[name=subject]').fill('Browser session')
    await page.locator('.support-desk textarea').fill('Please check the meter.')
    const [customerChat]=await Promise.all([page.waitForEvent('popup'),page.locator('.support-desk form button.btn-primary').click()])
    await customerChat.getByText('Please check the meter.').waitFor()
    const [agentChat]=await Promise.all([agentPage.waitForEvent('popup'),agentPage.locator('.support-case').filter({hasText:'Browser session'}).click()])
    await agentChat.getByRole('button',{name:/Accept session|Приеми сесията/}).click()
    await agentChat.locator('.desk-readings').waitFor()
    await agentChat.locator('textarea').fill('Your meter is connected.')
    await customerChat.locator('.desk-typing').waitFor()
    await agentChat.setViewportSize({width:390,height:460})
    const controls=await agentChat.locator('.desk-composer').boundingBox()
    assert.ok(controls.y>=0 && controls.y+controls.height<=461,'composer fits the popup')
    await agentChat.locator('textarea').press('Shift+Enter')
    assert.ok((await agentChat.locator('textarea').inputValue()).endsWith('\n'))
    await agentChat.locator('textarea').press('Enter')
    await customerChat.getByText('Your meter is connected.').waitFor()
    await customerChat.getByRole('button',{name:/End conversation|Приключи разговора/}).click()
    await customerChat.getByRole('button',{name:/Keep chatting|Продължи чата/}).click()
    await customerChat.getByRole('button',{name:/End conversation|Приключи разговора/}).click()
    await customerChat.getByRole('button',{name:/Yes, end chat|Да, приключи/}).click()
    await agentChat.locator('.desk-readings').waitFor({state:'detached'})
    await agentPage.locator('.support-case').waitFor({state:'detached'})
    await page.locator('.support-case').filter({hasText:'Browser session'}).waitFor({state:'detached'})
    await agentPage.getByRole('button',{name:/Live session history|История на живите сесии/}).click()
    await agentPage.getByRole('heading',{name:/Live session history|История на живите сесии/}).waitFor()
    await customerChat.getByRole('button',{name:'5 / 5',exact:true}).click()
    await customerChat.getByText(/Благодарим за оценката|Thank you for your rating/).waitFor()
    await customerChat.locator('a.session-home').click()
    await customerChat.locator('.dashboard').waitFor()
    await customerChat.close()
    await agentPage.context().close()
    for(const width of [390,768,1440]){
      await page.setViewportSize({width,height:900})
      for(const section of ['overview','trees','detail','insights','assistant','service','support','settings','profile']){
        const url = origin+'/#/'+section+'/'+tree.id
        await page.goto(url)
        const histories = new Set()
        const watch = req => {
          const match = new URL(req.url()).pathname.match(/\/trees\/\d+\/(readings|forecast|oxygen)$/)
          if(match) histories.add(match[1])
        }
        page.on('request',watch)
        await page.reload()
        await page.locator('.page-body').first().waitFor()
        await page.waitForLoadState('networkidle')
        assert.equal(new URL(page.url()).hash,new URL(url).hash)
        page.off('request',watch)
        const expected = {overview:['oxygen'],detail:['oxygen','readings'],insights:['forecast','oxygen']}
        assert.deepEqual([...histories].sort(),expected[section] || [],section+' data requests')
        assert.ok(await page.locator('h1').first().innerText())
        assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'overflow '+section+' '+width)
      }
    }
    await page.goto(origin+'/#/insights/'+tree.id)
    const charts=page.locator('.archive-chart')
    const powerCalendar=charts.nth(0).locator('.archive-picker > button')
    const oxygenCalendar=charts.nth(1).locator('.archive-picker > button')
    const powerLabel=await powerCalendar.innerText()
    await oxygenCalendar.click()
    await charts.nth(1).locator('.archive-month button').first().click()
    await charts.nth(1).locator('.archive-days button:enabled').first().click()
    assert.equal(await powerCalendar.innerText(),powerLabel)
    assert.notEqual(await oxygenCalendar.innerText(),powerLabel)
    await oxygenCalendar.click()
    await charts.nth(1).locator('.archive-reset').click()
    assert.equal(await oxygenCalendar.innerText(),powerLabel)
    await page.goto(origin+'/#/profile/'+tree.id)
    const animation = () => page.locator('.page-body').first().evaluate(el=>getComputedStyle(el).animationName)
    assert.match(await animation(),/section-arrive/)
    await page.emulateMedia({reducedMotion:'reduce'})
    assert.doesNotMatch(await animation(),/section-arrive/)
    await page.emulateMedia({reducedMotion:'no-preference'})
    const theme = () => page.locator('html').getAttribute('data-theme')
    const before = await theme()
    await page.locator('.theme-switch:visible').first().click()
    assert.notEqual(await theme(),before)
    const language = await page.locator('html').getAttribute('lang')
    await page.locator('.language-switch:visible').first().click()
    assert.notEqual(await page.locator('html').getAttribute('lang'),language)
    await page.locator('.profile-box form').first().locator('input').first().fill('Updated browser owner')
    await page.locator('.profile-box form').first().locator('button[type=submit]').click()
    await page.getByRole('heading',{name:'Updated browser owner'}).waitFor()
    const nav = page.locator('nav.side-nav button')
    await nav.nth(1).click()
    const map = page.locator('.tree-map-info')
    await map.locator('button.btn-outline').click()
    await map.locator('input').nth(0).fill('42.425')
    await map.locator('input').nth(1).fill('25.635')
    await map.locator('button.btn-primary').click()
    await page.locator('.tree-map-pin').waitFor()
    await page.reload()
    await page.locator('.tree-map-pin').waitFor()
    await map.locator('button.btn-primary').click()
    await page.locator('.detail-page').waitFor()
    await nav.nth(3).click()
    await page.locator('.prompt-chips button').first().click()
    await page.locator('.chat-bubble.assistant').waitFor()
    await page.reload()
    await page.locator('.chat-intro').waitFor()
    const listToggle=page.locator('[aria-controls="thread-list"]')
    if(await listToggle.getAttribute('aria-expanded')==='false')await listToggle.click()
    await page.locator('.thread-choice').first().click()
    await page.locator('.chat-bubble.assistant').waitFor()
    const history = page.locator('[aria-controls="thread-list"]')
    const expanded = await history.getAttribute('aria-expanded')
    await history.click()
    assert.notEqual(await history.getAttribute('aria-expanded'),expanded)
    await history.click()
    await nav.nth(4).click()
    await page.locator('.page-body button[title]').filter({has:page.locator('svg')}).first().click()
    await page.locator('.modal input[type=number]').fill('42')
    await page.locator('.modal button[type=submit]').click()
    await page.locator('.modal').waitFor({state:'hidden'})
    await nav.nth(1).click()
    await map.locator('button.btn-primary').click()
    page.once('dialog',dialog=>dialog.accept())
    await page.getByRole('button',{name:/^(Remove tree|Премахни дървото)$/}).click()
    await page.waitForURL(/#\/trees$/)
    const after = await page.request.get(origin+'/api/trees',{headers:{Authorization:'Bearer '+token}})
    assert.deepEqual(await after.json(),[])
    await page.locator('.profile-avatar-button').click()
    await page.locator('.profile-logout').click()
    await page.locator('#signin-email').fill('browser@example.com')
    await page.locator('#signin-password').fill('Test-password-7249')
    await page.locator('.signin-submit').click()
    await page.locator('.dashboard').waitFor()
    // The hosting workflow runs this test against a disposable PostgreSQL instance.
    require('node:child_process').execFileSync('psql',[
      'postgresql://postgres:ci_only@127.0.0.1:5432/postgres','-v','ON_ERROR_STOP=1','-c',
      "UPDATE users SET is_admin=true WHERE email='browser@example.com'",
    ])
    await page.goto(origin+'/?browser-check=admin#/admin')
    await page.locator('.page-body table').waitFor()
    await page.locator('.page-body > button.btn-primary').click()
    const downloads = page.locator('.page-body a[download]')
    await downloads.first().waitFor()
    for(const link of await downloads.all()){
      const [download] = await Promise.all([page.waitForEvent('download'),link.click()])
      assert.equal(await download.failure(),null)
    }
    const keysPanel = page.locator('.page-body section').filter({has:page.locator('a[download]')})
    await keysPanel.locator('button').click()
    for(const width of [390,768,1440]){
      await page.setViewportSize({width,height:900})
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'admin overflow '+width)
    }
    assert.deepEqual(errors,[])
  } finally { await browser.close() }
}
main().catch(error=>{console.error(error);process.exitCode=1})
